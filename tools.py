"""Agent-facing image tools.

Contract (per protoAgent's tool idiom): every tool returns a readable string —
markdown with the saved image's signed ``/media/`` URL on success (the console
renders it inline), or an ``Error: …`` line the model can act on. Never raises.

Image references: tools accept a prior result's media id (each success message
names it), a ``/media/<file>?sig=…`` URL, a ``data:image/...`` URL, or an
absolute file path. Generated bytes never enter the model's context as text —
when ``show_model`` is on they ride the multimodal envelope (#1930) instead.
"""

from __future__ import annotations

import base64
import re
from pathlib import Path

from langchain_core.tools import tool

from . import client, history, imaging

_registry = None
CFG: dict = {}

_DEFAULTS = {
    "gen_model": "protolabs/qwen-image",
    "fast_gen_model": "protolabs/qwen-image-2-1-turbo",
    "edit_model": "protolabs/qwen-image-edit",
    "fast_edit_model": "protolabs/qwen-image-edit-turbo",
    "chat_model": "protolabs/qwen-image-chat",
    "bgremove_model": "protolabs/qwen-image-bgremove",
    "region_model": "protolabs/qwen-image-region-edit",
    "outpaint_model": "protolabs/qwen-image-outpaint",
    "identity_model": "protolabs/krea2-identity-edit",
    "realism_identity_model": "protolabs/krea2-identity-edit-realism",
    "default_size": "1024x1024",
    "timeout_s": 300,
    "show_model": True,
}


def configure(registry) -> None:
    global _registry
    _registry = registry
    CFG.clear()
    CFG.update(_DEFAULTS)
    CFG.update({k: v for k, v in dict(getattr(registry, "config", {}) or {}).items() if v is not None})
    client.configure(CFG)


def get_tools() -> list:
    return [generate_image, edit_image, identity_edit, region_edit,
            remove_background, compose_images, outpaint_image]


# ---------------------------------------------------------------- helpers

def _resolve_image(ref: str) -> bytes:
    """Media id / signed /media/ URL / data URL / file path → raw bytes."""
    ref = (ref or "").strip()
    if not ref:
        raise ValueError("empty image reference")
    if ref.startswith("data:"):
        if "," not in ref:
            raise ValueError("malformed data URL")
        return base64.b64decode(ref.split(",", 1)[1])
    if "/media/" in ref:
        from infra.media import resolve_media

        name = ref.split("/media/", 1)[1].split("?", 1)[0]
        hit = resolve_media(name)
        if hit is None:
            raise ValueError(f"unknown media file {name!r}")
        return hit[0].read_bytes()
    if "/" not in ref:
        from infra.media import media_dir

        for f in sorted(media_dir().glob(f"{ref}.*")):
            if f.suffix != ".json" and not f.name.startswith("."):
                return f.read_bytes()
        raise ValueError(f"no media with id {ref!r} — use the id from a previous tool result")
    p = Path(ref)
    if p.is_file():
        return p.read_bytes()
    raise ValueError(f"can't resolve image reference {ref!r}")


def _person_data_url(raw: bytes) -> str:
    """Person ref → data URL small enough for the gateway's multipart cap.

    The LiteLLM proxy rejects any non-file form part over 1024KB, and the
    person ref rides a text field (data URL) because /v1/images/edits is
    single-image by spec. The server caps the person ref to ~1MP anyway, so
    shrinking client-side loses nothing."""
    b64 = base64.b64encode(raw).decode()
    if len(b64) <= 900_000:
        return "data:image/png;base64," + b64
    try:
        import io

        from PIL import Image

        img = Image.open(io.BytesIO(raw)).convert("RGB")
        img.thumbnail((1024, 1024))
        buf = io.BytesIO()
        img.save(buf, format="JPEG", quality=90)
        return "data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode()
    except ImportError:
        raise ValueError(
            "person reference exceeds the gateway's 1MB form-part cap and Pillow "
            "isn't installed to shrink it — run: protoagent plugin install-deps protobanana"
        )


def _dims(raw: bytes) -> str:
    wh = imaging.png_size(raw)
    return f"{wh[0]}x{wh[1]}" if wh else "image"


# Model sizes: multiples of 16 (VAE /8 + 2x2 patchify), within what the Qwen
# gen workflows render sanely.
_SIZE_STEP, _SIZE_MIN, _SIZE_MAX = 16, 256, 2048


def _snap_size(size: str) -> tuple[int, int]:
    """"WxH" → (w, h) snapped to the model's 16px grid and clamped to 256–2048.
    Raises ValueError on garbage so the tool can say what it expected."""
    m = re.fullmatch(r"\s*(\d+)\s*[x×*]\s*(\d+)\s*", size or "", re.IGNORECASE)
    if not m:
        raise ValueError(f"size must look like 1024x1024, got {size!r}")

    def snap(v: int) -> int:
        v = int(int(v) / _SIZE_STEP + 0.5) * _SIZE_STEP  # half-up, not banker's
        return max(_SIZE_MIN, min(_SIZE_MAX, v))

    return snap(m.group(1)), snap(m.group(2))


_CAPTION_MAX = 80
# Words that read badly right before an ellipsis ("…sitting in the…").
_DANGLING = {"a", "an", "the", "and", "or", "but", "of", "in", "on", "at", "to", "for",
             "with", "by", "from", "into", "onto", "over", "under", "as", "is", "are",
             "its", "their", "his", "her", "that", "which", "while"}


def _caption(text: str, prefix: str = "", limit: int = _CAPTION_MAX) -> str:
    """A short, clean alt-text caption from a prompt.

    Takes the first sentence (then the first comma/semicolon/dash clause if that
    is still long), cuts at a word boundary with an ellipsis, and drops dangling
    function words so it never ends "…sitting in t". Square brackets are
    swapped for parentheses so the markdown image syntax stays intact."""
    text = " ".join((text or "").split()).replace("[", "(").replace("]", ")")
    budget = max(12, limit - len(prefix))
    first = re.split(r"(?<=[.!?])\s", text, maxsplit=1)[0].rstrip(".!? ")
    if len(first) > budget:
        clause = re.split(r"\s*[,;:]\s+|\s+[—–-]\s+", first, maxsplit=1)[0]
        if len(clause) >= 16:  # a clause too short to mean anything isn't a caption
            first = clause
    if len(first) > budget:
        words = first[: budget + 1].split(" ")
        words = words[:-1] if len(words) > 1 else words  # last word may be cut
        while len(words) > 1 and words[-1].lower().strip(",;:") in _DANGLING:
            words.pop()
        first = " ".join(words).rstrip(",;:—–- ") + "…"
    return (prefix + first) if first else prefix.rstrip(": ") or "image"


def _finish(raw: bytes, caption: str, meta: dict, note: str = "") -> str:
    """Persist to the core media store and build the tool result.

    ``caption`` is the finished alt text (build it with ``_caption``); ``note``
    is appended to the first line (size/transparency caveats for the model)."""
    ref = _registry.save_media(raw, "image/png", meta)
    # Shared history (design §4): this agent render joins the Studio gallery with
    # source="agent". record_agent never raises — a history write must not break
    # a tool call (tools return readable strings, never raise).
    history.record_agent(ref.id, meta)
    alt = caption or "Generated image"
    text = (
        f"Done — {_dims(raw)} image saved as `{ref.id}`.{(' ' + note) if note else ''}\n\n"
        f"To show the user the image, include this markdown line VERBATIM "
        f"(exact URL, do not paraphrase it away) in your reply:\n"
        f"![{alt}]({ref.url})\n\n"
        f"Pass `{ref.id}` as the image reference to edit this result further."
    )
    if CFG.get("show_model", True):
        try:
            from graph.sdk import multimodal_tool_result

            return multimodal_tool_result(text, images=[{"b64": base64.b64encode(raw).decode(),
                                                         "mime": "image/png"}])
        except (ValueError, ImportError):
            pass  # over the core size cap (or old host) — inline markdown still renders
    return text


def _size_note(raw: bytes, want: tuple[int, int] | None, what: str) -> str:
    """Honest reporting: say so when the image isn't the size that was asked for."""
    got = imaging.png_size(raw)
    if not want or not got or tuple(got) == tuple(want):
        return ""
    return (f"Note: {what} {want[0]}x{want[1]} but the gateway returned "
            f"{got[0]}x{got[1]} — tell the user the actual size.")


def _transparency_note(prep: imaging.Prepared, restored: bool) -> str:
    if not prep.had_alpha:
        return ""
    if restored:
        return ("The input was transparent: it was edited on a white backdrop and its "
                "transparency re-applied (set keep_transparency=false to keep the filled-in "
                "backdrop instead).")
    return "The input was transparent: it was flattened onto white for the edit."


_UPSTREAM_DOWN = {502: "the gateway couldn't reach the image server",
                  503: "the image server is unavailable or overloaded",
                  504: "the image server didn't answer in time"}


def _looks_like_html(text: str) -> bool:
    head = (text or "").lstrip()[:200].lower()
    return head.startswith("<!doctype") or head.startswith("<html") or "<head" in head


def _err(e: Exception) -> str:
    """Exception → one readable line for the model. Never echoes an HTML page:
    a Cloudflare/proxy error body is noise to the model, and seeing raw HTML
    makes it tell users "the service is down" and retry in a loop."""
    try:
        import httpx

        if isinstance(e, httpx.HTTPStatusError):
            status = e.response.status_code
            if status == 524:
                return ("Error: the image server took longer than the gateway's ~100s limit "
                        "(HTTP 524). The job may still be running on the server — wait a minute "
                        "before retrying once, or try draft=true or a smaller size.")
            if status in _UPSTREAM_DOWN:
                return (f"Error: {_UPSTREAM_DOWN[status]} (HTTP {status}). This is usually "
                        "temporary — wait a minute before retrying once; don't retry in a loop.")
            detail = ""
            try:
                detail = (e.response.json().get("error") or {}).get("message", "")
            except ValueError:
                detail = e.response.text
            detail = "" if _looks_like_html(detail) else " ".join(str(detail).split())[:200]
            hint = " (alias missing from the gateway model_list?)" if status == 404 else ""
            return f"Error: gateway returned {status}{hint}: {detail or 'no detail'}"
        if isinstance(e, httpx.TimeoutException):
            return ("Error: gateway timed out — the render may still be queued on ComfyUI. "
                    "Try once more, or raise timeout_s in the protobanana plugin settings.")
    except ImportError:
        pass
    return f"Error: {type(e).__name__}: {e}"


_NO_CHANGE_REGION = ("Error: region_edit changed nothing — the region {region!r} wasn't found in "
                     "the image. Describe it differently (a short noun phrase for what is "
                     "visible, e.g. \"the red car\"), or use edit_image for a whole-image change.")
_NO_CHANGE_EDIT = ("Error: edit_image returned the image unchanged. Rephrase the instruction "
                   "more concretely, or use region_edit to target one object.")


def _seed(seed: int) -> int | None:
    return seed if seed >= 0 else None


# ------------------------------------------------------------------ tools

@tool
async def generate_image(prompt: str, size: str = "", seed: int = -1, negative_prompt: str = "",
                         draft: bool = False) -> str:
    """Generate an image from a text prompt.

    Args:
        prompt: What to draw — subject, style, composition, lighting. Renders
            legible text well (posters, logos, signs, title cards): put the exact
            words in double quotes, e.g. a poster saying "GRAND OPENING".
        size: WxH like "1024x1024" (default from plugin settings). Snapped to a
            multiple of 16 within 256–2048; the result states the actual size.
        seed: Fixed seed for reproducibility; -1 = random.
        negative_prompt: What to avoid (optional).
        draft: True = fast 8-step Turbo draft (~10s, great for prototyping/iterating);
            False = full-quality render (~30s). Use draft when the user wants
            quick concepts, options, or is iterating on a prompt.
    Returns markdown with the saved image and its media id, or a readable error.
    """
    try:
        model = CFG["fast_gen_model"] if draft else CFG["gen_model"]
        want = _snap_size(size or CFG["default_size"])
        raw = await client.generate(model, prompt, f"{want[0]}x{want[1]}",
                                    seed=_seed(seed), negative_prompt=negative_prompt or None)
        return _finish(raw, _caption(prompt), {"tool": "generate_image", "prompt": prompt,
                                               "model": model, "draft": draft},
                       note=_size_note(raw, want, "requested"))
    except Exception as e:
        return _err(e)


@tool
async def edit_image(image_ref: str, prompt: str, seed: int = -1, draft: bool = False,
                     keep_transparency: bool = True) -> str:
    """Edit an existing image with a natural-language instruction.

    Good for global/semantic changes ("make it night", "turn the car red",
    "watercolor style"). For changing ONE object precisely, prefer region_edit;
    for keeping a person's face intact, prefer identity_edit.

    Args:
        image_ref: A media id from a previous result, a /media/ URL, a data: URL, or a file path.
        prompt: The edit instruction.
        seed: Fixed seed; -1 = random.
        draft: True = fast 8-step Turbo edit (~10s vs ~38s) for quick iterations;
            False = full-quality edit. Use draft while the user is exploring
            variations, then re-run without it for the final.
        keep_transparency: For a transparent input (a cutout/sticker): True keeps
            the result transparent where the input was; set False when the edit
            should fill the empty area (e.g. "put it on a beach background").
    The result keeps the input's dimensions.
    Returns markdown with the edited image and its media id, or a readable error.
    """
    try:
        model = CFG["fast_edit_model"] if draft else CFG["edit_model"]
        prep = imaging.prepare(_resolve_image(image_ref))
        raw = await client.edit(model, prompt, prep.data, fields={"seed": _seed(seed)})
        if imaging.unchanged(prep.data, raw):
            return _NO_CHANGE_EDIT
        raw = imaging.finish_edit(raw, prep, keep_transparency=keep_transparency)
        note = " ".join(filter(None, (_transparency_note(prep, keep_transparency),
                                      _size_note(raw, prep.size, "the input was"))))
        return _finish(raw, _caption(prompt, "Edit: "),
                       {"tool": "edit_image", "prompt": prompt, "source": image_ref,
                        "model": model, "draft": draft}, note=note)
    except Exception as e:
        return _err(e)


@tool
async def identity_edit(image_ref: str, prompt: str, person_ref: str = "",
                        grounding_px: int = 0, seed: int = -1, realism: bool = False) -> str:
    """Edit or restage a photo while preserving a person's identity/likeness (Krea 2).

    Two modes:
    - Single-ref: image_ref is the person's photo; prompt restyles/restages them.
    - Two-ref: image_ref is the SCENE, person_ref is the PERSON to place into it
      (this ordering is load-bearing — swapping them degrades identity sharply).

    Args:
        image_ref: The photo to edit (single-ref) or the scene (two-ref).
        prompt: The edit/staging instruction.
        person_ref: The person's reference photo (two-ref mode only).
        grounding_px: Quality dial 512–1536 (0 = default 768, which is right
            for most edits). Lower favors the edit instruction; higher favors
            facial likeness but can make the model drop the subject from busy
            scenes — only raise it when likeness visibly needs the boost.
            Always state the subject's role explicitly in the prompt (e.g.
            "she is the foreground subject") when restaging into a new scene.
        seed: Fixed seed; -1 = random.
        realism: Set true when the subject is a human/portrait and the result
            should look like a natural photograph — adds a realism adapter that
            markedly improves face quality and skin texture. Leave false for
            stylized/illustrated/non-photographic results.
    Returns markdown with the result and its media id, or a readable error.
    """
    try:
        fields: dict = {"seed": _seed(seed)}
        if grounding_px:
            fields["grounding_px"] = grounding_px
        if person_ref.strip():
            fields["person_image"] = _person_data_url(imaging.prepare(_resolve_image(person_ref)).data)
        model = CFG["realism_identity_model"] if realism else CFG["identity_model"]
        prep = imaging.prepare(_resolve_image(image_ref))
        raw = await client.edit(model, prompt, prep.data, fields=fields)
        # Restaging moves the subject, so the input's alpha no longer lines up:
        # flatten-only (no black voids), keep the size when the shape held.
        raw = imaging.finish_edit(raw, prep)
        return _finish(raw, _caption(prompt, "Edit: "),
                       {"tool": "identity_edit", "prompt": prompt,
                        "two_ref": bool(person_ref.strip()), "realism": realism},
                       note=_transparency_note(prep, False))
    except Exception as e:
        return _err(e)


@tool
async def region_edit(image_ref: str, region: str, prompt: str, seed: int = -1,
                      keep_transparency: bool = True) -> str:
    """Edit ONE region/object of an image, leaving everything else untouched
    (SAM-grounded segmentation + inpaint).

    Args:
        image_ref: The image to edit (media id, /media/ URL, data: URL, or path).
        region: What to target, as a short noun phrase — "the red car", "her hat".
        prompt: What the region should become.
        seed: Fixed seed; -1 = random.
        keep_transparency: For a transparent input (a cutout/sticker): True keeps
            the result transparent where the input was; set False when the edit
            should fill the empty area. To DELETE part of a cutout, use
            remove_background on the result instead of painting it white.
    Returns markdown with the result and its media id, or a readable error.
    """
    try:
        prep = imaging.prepare(_resolve_image(image_ref))
        raw = await client.edit(CFG["region_model"], prompt, prep.data,
                                fields={"grounding": region, "seed": _seed(seed)})
        if imaging.unchanged(prep.data, raw):
            return _NO_CHANGE_REGION.format(region=region)
        raw = imaging.finish_edit(raw, prep, keep_transparency=keep_transparency)
        return _finish(raw, _caption(f"{region} → {prompt}", "Edit: "),
                       {"tool": "region_edit", "region": region, "prompt": prompt},
                       note=_transparency_note(prep, keep_transparency))
    except Exception as e:
        return _err(e)


@tool
async def remove_background(image_ref: str) -> str:
    """Remove an image's background, leaving the subject on transparency
    (sticker/cutout).

    Args:
        image_ref: The image (media id, /media/ URL, data: URL, or path).
    Returns markdown with the cutout and its media id, or a readable error.
    """
    try:
        prep = imaging.prepare(_resolve_image(image_ref))
        raw = await client.edit(CFG["bgremove_model"], "remove background", prep.data)
        # Strip the old background's colour from the soft edges (halo), using
        # the image that was actually matted as the reference.
        raw = imaging.defringe(raw, prep.data)
        return _finish(raw, "Cutout, background removed",
                       {"tool": "remove_background", "source": image_ref})
    except Exception as e:
        return _err(e)


@tool
async def compose_images(image_refs: list[str], prompt: str) -> str:
    """Compose 2–3 reference images into one new image (subjects, products,
    styles combined per the prompt).

    There is NO size or aspect-ratio control here: the gateway's compose
    (multiref) route takes no size, so don't promise the user "portrait" or
    "16:9" from this tool. To change the shape afterwards, use outpaint_image
    (add margins) on the result.

    Args:
        image_refs: 2–3 references (media ids, /media/ URLs, data: URLs, or paths).
        prompt: How to combine them — who/what goes where, style, setting.
    Returns markdown with the composition and its media id, or a readable error.
    """
    try:
        refs = [r for r in (image_refs or []) if str(r).strip()]
        if not 2 <= len(refs) <= 3:
            return f"Error: compose_images needs 2–3 image references, got {len(refs)}."
        raw = await client.chat_compose(CFG["chat_model"], prompt,
                                        [imaging.prepare(_resolve_image(r)).data for r in refs])
        return _finish(raw, _caption(prompt, "Composite: "),
                       {"tool": "compose_images", "prompt": prompt, "refs": len(refs)})
    except Exception as e:
        return _err(e)


@tool
async def outpaint_image(image_ref: str, prompt: str = "", left: int = 0, top: int = 0,
                         right: int = 0, bottom: int = 0, seed: int = -1) -> str:
    """Extend an image's canvas outward (outpaint) by pixel margins.

    Args:
        image_ref: The image (media id, /media/ URL, data: URL, or path).
        prompt: What the new areas should contain (empty = continue the scene).
        left: Pixels to add on the left.
        top: Pixels to add on top.
        right: Pixels to add on the right.
        bottom: Pixels to add on the bottom.
        seed: Fixed seed; -1 = random.
    Returns markdown with the extended image and its media id, or a readable error.
    """
    try:
        if not any((left, top, right, bottom)):
            return "Error: give at least one non-zero margin (left/top/right/bottom)."
        prep = imaging.prepare(_resolve_image(image_ref))
        raw = await client.edit(CFG["outpaint_model"], prompt or "extend the scene", prep.data,
                                fields={"left": left, "top": top, "right": right,
                                        "bottom": bottom, "seed": _seed(seed)})
        return _finish(raw, _caption(prompt, "Extended: ") if prompt else "Extended image",
                       {"tool": "outpaint_image", "prompt": prompt},
                       note=_transparency_note(prep, False))
    except Exception as e:
        return _err(e)
