@tool
async def generate_image(prompt: str, size: str = "", seed: int = -1, negative_prompt: str = "",
                         draft: bool = False) -> str:
    """Generate an image from a text prompt.

    Not for a new size or shape of an image you already made ("a square version of
    the same design", "a social card from this banner"): generating again redraws a
    different design. Use outpaint_image on the existing image instead.

    Args:
        prompt: What to draw — subject, style, composition, lighting. Renders
            legible text well (posters, logos, signs, title cards): put the exact
            words in double quotes, e.g. a poster saying "GRAND OPENING".
        size: WxH like "1024x1024" (default from plugin settings). Snapped to a
            multiple of 16 within 256–2048; the result states the actual size.
        seed: Fixed seed for reproducibility; -1 = random.
        negative_prompt: What to avoid (optional).
        draft: True = fast 8-step Turbo draft (~10s, great for prototyping/iterating);
            False = full-quality render (~30s). Use draft when the user wants
            quick concepts, options, or is iterating on a prompt.
    Returns markdown with the saved image and its media id, or a readable error.
    """
    try:
        model = CFG["fast_gen_model"] if draft else CFG["gen_model"]
        want = _snap_size(size or CFG["default_size"])
        raw = await client.generate(model, prompt, f"{want[0]}x{want[1]}",
                                    seed=_seed(seed), negative_prompt=negative_prompt or None)
        # meta doubles as the shared-history re-run record: the resolved size and
        # the seed are kept (in jobs._dispatch's param shape) so a Gallery re-run
        # reproduces a locked-seed render (design §3.1 / S2).
        meta = {"tool": "generate_image", "model": model, "prompt": prompt,
                "size": f"{want[0]}x{want[1]}", "seed": seed, "draft": draft}
        if negative_prompt:
            meta["negative_prompt"] = negative_prompt
        return _finish(raw, _caption(prompt), meta, note=_size_note(raw, want, "requested"))
    except Exception as e:
        return _err(e)


@tool
async def edit_image(image_ref: str, prompt: str, seed: int = -1, draft: bool = False,
                     keep_transparency: bool = True) -> str:
    """Edit an existing image with a natural-language instruction.

    Good for global/semantic changes ("make it night", "turn the car red",
    "watercolor style") and for restyling or restaging a person ("put him on a
    beach at sunset") — it keeps their face and likeness. For changing ONE
    object precisely, prefer region_edit; to place a person from one photo into
    another scene, use compose_images with both images.

    For product or listing photos where the product must stay exactly as
    photographed, use stage_product instead.

    Args:
        image_ref: A media id from a previous result, a /media/ URL, a data: URL, or a file path.
        prompt: The edit instruction.
        seed: Fixed seed; -1 = random.
        draft: True = fast 8-step Turbo edit (~10s vs ~38s) for quick iterations;
            False = full-quality edit. Use draft while the user is exploring
            variations, then re-run without it for the final.
        keep_transparency: For a transparent input (a cutout/sticker): True keeps
            the result transparent where the input was; set False when the edit
            should fill the empty area (e.g. "put it on a beach background").
    The result keeps the input's dimensions.
    Returns markdown with the edited image and its media id, or a readable error.
    """
    try:
        model = CFG["fast_edit_model"] if draft else CFG["edit_model"]
        source = _resolve_image(image_ref)
        prep = imaging.prepare(source)
        raw = await client.edit(model, prompt, prep.data, fields={"seed": _seed(seed)})
        if imaging.unchanged(prep.data, raw):
            return _NO_CHANGE_EDIT
        raw = imaging.finish_edit(raw, prep, keep_transparency=keep_transparency)
        note = " ".join(filter(None, (_transparency_note(prep, keep_transparency),
                                      _size_note(raw, prep.size, "the input was"))))
        return _finish(raw, _caption(prompt, "Edit: "),
                       {"tool": "edit_image", "model": model, "image": image_ref,
                        "prompt": prompt, "seed": seed, "draft": draft,
                        "keep_transparency": keep_transparency}, note=note,
                       source_bytes=source, source_name=_ref_name(image_ref))
    except Exception as e:
        return _err(e)


def _subject_not_found(subject: str) -> str:
    """The background swap found no product for ``subject`` and regenerated the whole photo."""
    return (f"Error: couldn't find {subject!r} in the photo, so nothing was kept (the result "
            "would have been a different object). Retry with subject set to a short noun "
            "phrase for what's actually in the photo, e.g. \"the mug\" or \"the blue bottle\".")


def _staged_note(before: bytes, after: bytes) -> str:
    """Tell the agent the product is the photo's own pixels, and that this was checked.

    Without this the agent reads the original photo's colour cast or camera angle
    (plain to see once the background is white) as the tool changing the product,
    retries, and falls back to the editor that really does change it. No
    percentage: "N% of the image" read as "only part of the product is kept"."""
    share = imaging.preserved_fraction(before, after)
    checked = " (checked: the product area matches the input pixel-for-pixel)" if share else ""
    return ("Verified: the whole product is copied from the original photo pixel-for-pixel; "
            "only the background was generated" + checked + ". If its colour or shape looks "
            "different next to the new background, that's the original photo's lighting and "
            "camera angle, not a change, so don't retry, switch tools or report it as changed.")


@tool
async def stage_product(image_ref: str, scene: str, subject: str = "the product",
                        seed: int = -1) -> str:
    """Put a product or object from a photo onto a new background or into a new scene (white studio background, kitchen counter, wooden table...) while keeping the product exactly as photographed: only the background is generated, the product's own pixels are kept. Use this for shop and listing photos. subject: a short noun phrase for the product ("the mug"). scene: the new background, including lighting and a natural contact shadow. If the gateway lacks the background-swap alias, falls back to the legacy editor and labels the result as a re-render that may change the product."""
    try:
        source = _resolve_image(image_ref)
        prep = imaging.prepare(source)
        try:
            raw = await client.edit(CFG["bgswap_model"], scene, prep.data,
                                    fields={"grounding": subject, "seed": _seed(seed)})
        except httpx.HTTPStatusError as exc:
            # Older gateways may not have deployed bgswap yet. Preserve the
            # previous chat staging path, but never describe its re-render as
            # pixel-preserving. Other failures must not trigger another render.
            message = exc.response.text.lower()
            missing = exc.response.status_code == 404 or (
                exc.response.status_code == 400 and any(term in message for term in (
                    "invalid model name", "model not found", "unknown model", "alias missing",
                ))
            )
            if not missing or CFG["bgswap_model"] == CFG["edit_model"]:
                raise
            prompt = (f"Place {subject} in this scene: {scene}. "
                      "Keep the product's shape, colour and details unchanged.")
            raw = await client.edit(CFG["edit_model"], prompt, prep.data,
                                    fields={"seed": _seed(seed)})
            if imaging.unchanged(prep.data, raw):
                return _NO_CHANGE_EDIT
            raw = imaging.finish_edit(raw, prep, keep_transparency=False)
            return _finish(
                raw, _caption(scene, "Staged: "),
                {"tool": "edit_image", "model": CFG["edit_model"], "image": image_ref,
                 "prompt": prompt, "seed": seed, "draft": False, "keep_transparency": False},
                note=("Background-only staging is unavailable on this gateway; used the legacy "
                      "editor. This is a re-render and may change the product. Include this "
                      "limitation when delivering the image; its original pixels are not guaranteed."),
                source_bytes=source, source_name=_ref_name(image_ref),
            )
        if imaging.subject_missing(prep.data, raw):
            return _subject_not_found(subject)
        return _finish(raw, _caption(scene, "Staged: "),
                       {"tool": "stage_product", "model": CFG["bgswap_model"],
                        "image": image_ref, "scene": scene, "subject": subject, "seed": seed},
                       note=_staged_note(prep.data, raw),
                       source_bytes=source, source_name=_ref_name(image_ref))
    except Exception as e:
        return _err(e)


@tool
async def region_edit(image_ref: str, region: str, prompt: str, seed: int = -1,
                      keep_transparency: bool = True) -> str:
    """Edit ONE region/object of an image, leaving everything else untouched
    (SAM-grounded segmentation + inpaint).

    Args:
        image_ref: The image to edit (media id, /media/ URL, data: URL, or path).
        region: What to target, as a short noun phrase — "the red car", "her hat".
        prompt: What the region should become.
        seed: Fixed seed; -1 = random.
        keep_transparency: For a transparent input (a cutout/sticker): True keeps
            the result transparent where the input was; set False when the edit
            should fill the empty area. To DELETE part of a cutout, use
            remove_background on the result instead of painting it white.
    Returns markdown with the result and its media id, or a readable error.
    """
    try:
        source = _resolve_image(image_ref)
        prep = imaging.prepare(source)
        raw = await client.edit(CFG["region_model"], prompt, prep.data,
                                fields={"grounding": region, "seed": _seed(seed)})
        if imaging.unchanged(prep.data, raw):
            return _NO_CHANGE_REGION.format(region=region)
        raw = imaging.finish_edit(raw, prep, keep_transparency=keep_transparency)
        return _finish(raw, _caption(f"{region} → {prompt}", "Edit: "),
                       {"tool": "region_edit", "model": CFG["region_model"],
                        "image": image_ref, "region": region, "prompt": prompt,
                        "seed": seed, "keep_transparency": keep_transparency},
                       note=_transparency_note(prep, keep_transparency),
                       source_bytes=source, source_name=_ref_name(image_ref))
    except Exception as e:
        return _err(e)


@tool
async def remove_background(image_ref: str) -> str:
    """Remove an image's background, leaving the subject on transparency
    (sticker/cutout).

    Use ONLY when the user needs real transparency: a sticker, a logo, or a
    cut-out to composite elsewhere. For a product or object photo on a white
    background or in a new scene, call stage_product on the ORIGINAL photo instead
    (don't cut out first). This tool's segmentation gives rough edges on glossy,
    reflective or fine-edged subjects.

    Args:
        image_ref: The image (media id, /media/ URL, data: URL, or path).
    Returns markdown with the cutout and its media id, or a readable error.
    """
    try:
        source = _resolve_image(image_ref)
        prep = imaging.prepare(source)
        raw = await client.edit(CFG["bgremove_model"], "remove background", prep.data)
        # Strip the old background's colour from the soft edges (halo), using
        # the image that was actually matted as the reference.
        raw = imaging.defringe(raw, prep.data)
        return _finish(raw, "Cutout, background removed",
                       {"tool": "remove_background", "model": CFG["bgremove_model"],
                        "image": image_ref},
                       source_bytes=source, source_name=_ref_name(image_ref))
    except Exception as e:
        return _err(e)


@tool
async def compose_images(image_refs: list[str], prompt: str) -> str:
    """Compose 2–10 reference images into one new image (subjects, products,
    styles combined per the prompt).

    There is NO size or aspect-ratio control here: the gateway's compose
    (multiref) route takes no size, so don't promise the user "portrait" or
    "16:9" from this tool. To change the shape afterwards, use outpaint_image
    (add margins) on the result.

    Args:
        image_refs: 2–10 references (media ids, /media/ URLs, data: URLs, or paths).
        prompt: How to combine them — who/what goes where, style, setting.
            Name the references by position: "the man from <image1> sitting
            on the sofa in <image2>". This is also how to put a person into
            another photo's scene while keeping their likeness.
    Returns markdown with the composition and its media id, or a readable error.
    """
    try:
        refs = [r for r in (image_refs or []) if str(r).strip()]
        if not 2 <= len(refs) <= 10:
            return f"Error: compose_images needs 2–10 image references, got {len(refs)}."
        resolved = [_resolve_image(r) for r in refs]
        raw = await client.chat_compose(CFG["compose_model"], prompt,
                                        [imaging.prepare(b).data for b in resolved])
        # Keep the actual refs (not just their count) so a Gallery re-run of a
        # compose record feeds jobs._dispatch the images again (design §3.1 / S2).
        # The first ref is the lineage parent (history._primary_ref).
        return _finish(raw, _caption(prompt, "Composite: "),
                       {"tool": "compose_images", "model": CFG["compose_model"],
                        "images": refs, "prompt": prompt},
                       source_bytes=resolved[0], source_name=_ref_name(refs[0]))
    except Exception as e:
        return _err(e)


@tool
async def outpaint_image(image_ref: str, prompt: str = "", left: int = 0, top: int = 0,
                         right: int = 0, bottom: int = 0, seed: int = -1,
                         target: str = "") -> str:
    """Extend an image's canvas outward (outpaint) by pixel margins.

    The right tool for the SAME design in another shape or size: a square social
    card from a wide banner, a tall story from a square, a wider hero. It keeps the
    existing artwork exactly and only adds canvas. For a new shape, pass target
    (e.g. target="1:1", "4:5", "16:9" or "1024x1024") and leave the margins at 0:
    the tool works out centred margins itself, so you don't need the image's size.
    Describe the new areas in prompt (e.g. "extend the dark background, plain, no
    new objects or text").

    Args:
        image_ref: The image (media id, /media/ URL, data: URL, or path).
        prompt: What the new areas should contain (empty = continue the scene).
        left: Pixels to add on the left.
        top: Pixels to add on top.
        right: Pixels to add on the right.
        bottom: Pixels to add on the bottom.
        seed: Fixed seed; -1 = random.
        target: Aspect ratio "W:H" or size "WxH" to extend to (centred). Overrides the
            margins. A WxH target is extended to that aspect, then resized to WxH.
    Returns markdown with the extended image and its media id, or a readable error.
    """
    try:
        source = _resolve_image(image_ref)
        resize_to = None
        if target:
            plan = imaging.margins_for_target(source, target)
            if plan is None:
                return (f"Error: couldn't read target {target!r}; use an aspect like \"1:1\" "
                        "or a size like \"1024x1024\".")
            (left, top, right, bottom), resize_to = plan
            if not any((left, top, right, bottom)) and resize_to is None:
                return f"Error: the image is already {target}; nothing to extend."
        if not any((left, top, right, bottom)):
            if resize_to is None:
                return "Error: give at least one non-zero margin (left/top/right/bottom) or a target."
            # Already the target's shape, just a different size: resize only, no outpaint.
            return _finish(imaging.resize_to(source, resize_to), f"Resized to {target}",
                           {"tool": "outpaint_image", "model": CFG["outpaint_model"],
                            "image": image_ref, "prompt": prompt, "left": 0, "top": 0,
                            "right": 0, "bottom": 0, "seed": seed, "target": target},
                           source_bytes=source, source_name=_ref_name(image_ref))
        prep = imaging.prepare(source)
        raw = await client.edit(CFG["outpaint_model"], prompt or "extend the scene", prep.data,
                                fields={"left": left, "top": top, "right": right,
                                        "bottom": bottom, "seed": _seed(seed)})
        if resize_to is not None:
            raw = imaging.resize_to(raw, resize_to)
        return _finish(raw, _caption(prompt, "Extended: ") if prompt else "Extended image",
                       {"tool": "outpaint_image", "model": CFG["outpaint_model"],
                        "image": image_ref, "prompt": prompt, "left": left, "top": top,
                        "right": right, "bottom": bottom, "seed": seed, "target": target},
                       note=_transparency_note(prep, False),
                       source_bytes=source, source_name=_ref_name(image_ref))
    except Exception as e:
        return _err(e)


@tool
async def inpaint_image(image_ref: str, mask_ref: str, prompt: str, seed: int = -1) -> str:
    """Repaint exactly the masked area of an image; everything else is kept
    pixel-for-pixel.

    Needs a mask the same size as the image: either transparent = edit /
    opaque = keep, or black-and-white with white = edit. You can't draw a
    mask yourself — if the user can NAME the area ("the sky", "his shirt"),
    use region_edit instead (it finds the mask from the words). For a
    freehand area, point the user at the Studio's Inpaint mask painter, or
    use a mask image they attached.

    Args:
        image_ref: The image (media id, /media/ URL, data: URL, or path).
        mask_ref: The mask, same size as the image (same reference forms).
        prompt: What to paint into the masked area.
        seed: Fixed seed; -1 = random.
    Returns markdown with the result and its media id, or a readable error.
    """
    try:
        source = _resolve_image(image_ref)
        mask = imaging.validate_mask(_resolve_image(mask_ref), source)
        ref = _registry.save_media(mask, "image/png",
                                   {"op": "mask", "image": image_ref,
                                    "polarity": "transparent=edit"})
        prep = imaging.prepare(source)
        raw = await client.edit(CFG["inpaint_model"], prompt, prep.data, mask=mask,
                                fields={"seed": _seed(seed)})
        return _finish(raw, _caption(prompt, "Inpaint: "),
                       {"tool": "inpaint_image", "model": CFG["inpaint_model"],
                        "image": image_ref, "mask": ref.id, "prompt": prompt, "seed": seed},
                       source_bytes=source, source_name=_ref_name(image_ref))
    except Exception as e:
        return _err(e)


